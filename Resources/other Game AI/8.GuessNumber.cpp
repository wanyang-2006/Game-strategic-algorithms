/*
  问题：根据若干次猜测记录 (A, B, C) 反推真实四位数。
  含义：
  1) A 是玩家猜的四位数；
  2) B 是“猜对的数字个数”（不要求位置正确）；
  3) C 是“数字和位置都正确的个数”。

  本程序思路：
  1) 枚举所有四位数答案 1000~9999；
  2) 对每条问答记录，计算该候选答案对应的 (B, C)；
  3) 若候选答案满足全部记录，则是可行解；
  4) 若可行解唯一输出该解，否则输出 Not sure。
*/

#include<stdio.h> // 使用 C 标准输入输出

typedef struct res // 存放一次比较得到的结果
{
  int a, b; // a: 数字正确总数(B), b: 位置正确数(C)
}Res;

Res judge(int an, int gu) // an: 假设答案，gu: 一次猜测
{
  int i;                 // 循环变量
  int ans[4];            // 保存答案的 4 个数位
  int guess[4];          // 保存猜测的 4 个数位
  Res r;                 // 本次比较的返回结果
  r.a = 0, r.b = 0;      // 先清零

  int n[10] = {0};       // 数字桶：n[d] 表示答案中数字 d 剩余可匹配次数

  // 把整数拆成 4 位，按下标 0~3 对应千百十个位置
  for(i = 3; i >= 0; i--)
  {
    ans[i] = an % 10;    // 取答案当前最低位
    an = an / 10;        // 去掉已取出的最低位
    guess[i] = gu % 10;  // 取猜测当前最低位
    gu = gu / 10;        // 去掉已取出的最低位
  }

  // 第一遍：统计答案各数字出现次数；同时计算位置正确数 b
  for(i = 0; i < 4; i++)
  {
    n[ans[i]]++;               // 答案数字入桶
    if(ans[i] == guess[i])     // 同位置同数字
      r.b++;                   // 位置正确数 +1
  }

  // 第二遍：计算数字正确总数 a（考虑重复数字，靠桶计数控制）
  for(i = 0; i < 4; i++)
  {
    if(n[guess[i]] > 0)        // 若该猜测数字在答案剩余桶中还存在
    {
      n[guess[i]]--;           // 消耗一个匹配名额
      r.a++;                   // 数字正确总数 +1
    }
  }

  return r; // 返回该答案-猜测对的 (a, b)
}

int main()
{
  int N;                // 当前测试组的问答条数
  int i, m;             // 循环变量
  int n;                // 当前候选答案满足了多少条约束
  int f;                // 可行解个数计数器
  Res re;               // 保存一次 judge 的结果
  int key, text[101][3];// text[k]: 第 k 条记录，依次存 A、B、C

  freopen("in.txt", "r", stdin); // 从文件读取输入（本地调试用）

  while(scanf("%d", &N) && N != 0) // N=0 结束输入
  {
    for(i = 0; i < N; i++) // 读取 N 条问答记录
    {
      scanf("%d%d%d", &text[i][0], &text[i][1], &text[i][2]);
    }

    f = 0; // 每组数据开始时，先认为还没有找到可行解

    // 枚举所有四位候选答案（允许数字重复）
    for(i = 1000; i < 10000; i++)
    {
      n = 0; // 统计该候选答案当前满足的记录条数

      // 逐条验证当前候选答案是否符合所有历史问答
      for(m = 0; m < N; m++)
      {
        re = judge(i, text[m][0]); // 计算“候选答案 i”对“猜测 A”的 (a,b)

        // 若结果与输入给定的 (B,C) 完全一致，则该条记录通过
        if(re.a == text[m][1] && re.b == text[m][2])
          n++;
        else
          break; // 只要一条不满足，这个候选答案就淘汰
      }

      // 若 N 条记录都通过，则当前 i 是一个可行解
      if(n == N)
      {
        key = i; // 记录该可行解
        f++;     // 可行解数量 +1
      }

      // 若可行解超过 1 个，就不唯一了，可以提前结束枚举
      if(f > 1)
        break;
    }

    // 按题意输出：唯一解就输出该数，否则输出 Not sure
    if(f == 1) printf("%d\n", key);
    else printf("Not sure\n");
  }

  return 0; // 程序正常结束
}